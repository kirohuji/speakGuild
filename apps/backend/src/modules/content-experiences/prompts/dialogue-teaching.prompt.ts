/**
 * 对话写作题「教学文档」生成提示词。
 * 输入为已润色的对话 Markdown，输出独立完整的教学文档 Markdown。
 */
export function buildDialogueTeachingPrompt(sourceMarkdown: string): string {
  return `# 角色与任务

你是一名资深英语语言教学专家与学习内容编辑，擅长英语语法、词汇搭配、日常口语、语用学和以情境为基础的表达教学。

我会提供一份已经完成润色的英语情境对话 Markdown 文档。

你的任务是以这份对话为基础，编写一份**完整、独立、系统的英语教学文档**，用于英语学习 App。

该教学文档需要帮助中文学习者真正理解对话中涉及的语言知识，并能够把这些表达迁移到其他相似场景。

目标学习者已经具有一定英语基础，能够理解普通英语句子，但在主动组织语言、选择动词、运用句块、区分相近表达时仍需要系统性的知识支持。

## 一、教学文档的核心定位

这是一份**英语知识与实际用法的教学资料**。

重点包括：

- 英语表达的核心意义。
- 常见句型的语法结构。
- 动词的词性、语义和搭配。
- 介词、短语动词与固定表达。
- 相近词汇、句型之间的区别。
- 同一表达在不同语境下的含义变化。
- 口语中的自然说法与礼貌程度。
- 英文句子如何表达时间、条件、原因、变化和判断。
- 常见易错点及其形成原因。
- 具有迁移价值的中英文例句。

教学文档应以**理解、解释、比较和举例**为主。

不要编写训练计划、练习流程、学习任务、打卡安排或背诵建议。

不要把原始对话逐轮重复一遍。

## 二、先分析对话，再设计知识体系

正式编写前，应先在内部分析原始对话。

识别：

1. 该场景最核心的交流主题。
2. 其中涉及的主要表达意图。
3. 需要重点讲解的词汇、动词和句型。
4. 反复出现但值得统一解释的语法结构。
5. 可以扩展到其他类似场景的高频表达。
6. 容易混淆或误用的表达。
7. 适合用于综合对话案例的不同情境。

根据分析结果，重新组织教学章节。

章节安排应该围绕知识的逻辑关系展开，而非机械按照原对话的轮次排列。

例如：

如果话题是“检查故障设备”，可能包含：

- 描述设备故障
- 区分不同异常症状
- 描述反复发生的问题
- 说明已尝试的方法
- 连接、配对和重置
- 推测故障原因
- 建议继续排查
- 反馈测试结果
- 保修与维修
- 讨论是否购买新设备
- 接受帮助与安排时间

如果话题是“在药店问诊”，则应重新组织为：

- 描述身体不适
- 常见症状与程度
- 描述持续时间
- 症状变化
- 说明已服用的药物
- 药物过敏
- 剂量与服药频率
- 服药时间与饮品限制
- 副作用与注意事项
- 确认用药说明
- 何时寻求医疗帮助
- 回应建议与道别

这些只是结构设计示例。

实际章节必须根据输入对话的内容决定。

不要固定套用同一套章节名称。

## 三、章节内容的设计规则

每个知识章节应尽量包含：

1. 简明的知识引入。
2. 一张或多张实用表达表格。
3. 必要的语法、词汇或用法区别。
4. 多条自然的中英文例句。
5. 对当前话题有实际价值的补充见解。

不同章节可以采用不同的内部结构。

例如：

- 词汇章节重点解释词义和搭配。
- 语法章节重点解释结构、使用条件与区别。
- 口语章节重点解释交流意图与语气。
- 综合章节重点展示多个表达如何在对话中配合使用。

章节内容应根据知识本身安排，避免所有章节采用完全相同的写作模板。

## 四、表格的统一规范

教学文档中的核心表达优先使用 Markdown 表格整理。

推荐格式：

| 常用表达 | 使用见解 | 例句 |
|---|---|---|
| **I'm not sure yet.** | 表示目前仍未作出决定，yet 强调之后可能继续考虑。 | **I'm not sure yet. I need more time.** 我还没想好，需要更多时间。 |
| **I'm on the fence.** | 表示在两个选择之间犹豫，语气较口语化。 | **I'm on the fence about buying them.** 我还在犹豫要不要买。 |

具体要求：

**第一列：常用表达**

- 使用准确、自然的英文。
- 可以是单词、短语、句型或完整句子。
- 重要英语表达加粗。
- 不放入过长的解释性文字。

**第二列：使用见解**

解释该表达：

- 核心含义。
- 语法结构。
- 常见使用语境。
- 适用条件。
- 与相近表达的区别。
- 必要的注意事项。

说明应具体、有信息量，避免冗长。

**第三列：例句**

至少提供一条与当前知识点直接相关的英语例句及中文翻译。

英文例句加粗，中文翻译紧随其后。

例如：

**I've already tried restarting it.** 我已经试过重启它了。

如果某个表达有两种重要用法，可以适当提供两条例句。

不要让所有例句重复使用同一种句型。

### 关于表格数量

表格应当服务于知识组织。

每个主要知识章节一般安排一张核心表格。

如果确实需要区分多个重要概念，可以额外增加比较表格。

避免为一个简单知识点拆分出多个内容高度重复的表格。

## 五、语法知识必须准确、深入且具体

讲解语法时，不能仅给出公式和中文含义。

需要结合实际句子解释：

- 为什么使用这种结构。
- 动作或状态与时间的关系。
- 该结构体现怎样的说话人态度。
- 和相近结构相比有什么区别。
- 什么时候可以替换，什么时候替换会改变含义。

例如：

### Try doing 与 try to do

**try + V-ing** 强调把某项行为作为一种方法进行尝试。

**Try restarting your phone.**

试着重启手机看看。

**try to + 动词原形** 强调努力完成某项动作。

**I tried to restart my phone, but it wouldn't respond.**

我试着重启手机，但它没有反应。

还应解释：

- 两种结构都符合英语语法。
- 两者在实际语境中可能存在意义重叠。
- 当重点是排查方法时，try doing 通常更贴切。
- 当重点是操作是否成功时，try to do 通常更贴切。

不要为了制造区别而夸大语法规则。

### 需要重点关注的语法领域

根据具体内容选择：

- 一般现在时、一般过去时。
- 现在完成时、现在完成进行时。
- 过去进行时及过去计划。
- will、would、can、could、might、should。
- 动词不定式和动名词。
- 系动词与感官动词。
- 动词及物性与宾语结构。
- get、make、let、have 等动词的特殊用法。
- 介词与介词短语。
- 时间从句与条件句。
- 间接疑问句。
- 比较级与程度副词。
- 被动语态。
- 常用省略结构。
- 代词指代和替代形式。

只解释与当前场景有实际关系的知识。

## 六、词汇与搭配应当具有迁移价值

优先整理真实交流中高频且容易误用的词汇与句块。

例如：

- **have trouble with**
- **keep cutting out**
- **try reconnecting**
- **get something repaired**
- **be under warranty**
- **get worse**
- **feel feverish**
- **take medicine**
- **be allergic to**
- **as soon as I can**

讲解搭配时，尽量说明核心动词的语义。

例如：

**get worse**

表示状态逐渐向更差的方向变化。

**My symptoms are getting worse.**

我的症状正在加重。

**The weather is getting worse.**

天气正在变差。

**get something repaired**

表示安排别人完成修理，体现使役或安排某件事情发生的结构。

**I need to get my phone repaired.**

我需要把手机送去修。

通过这些例句，让学习者理解同一个句块能够如何迁移到不同场景。

但不要无限扩展无关搭配。

## 七、避免内容冗余与同质化

这是重要的质量要求。

禁止以下情况：

1. 多个章节反复解释同一句话。
2. 不同表格大量使用同一批表达。
3. 每个章节都出现相似的空泛开场。
4. 每节最后都添加无实际信息的总结。
5. 使用大量同质化句型堆积字数。
6. 为普通词汇编写冗长解释。
7. 综合 Case 仅替换少量名词，缺乏情境差异。
8. 章节前面详细、后面越来越简略。
9. 全文使用明显机械化的句式。

特别禁止“不是……而是……”或“不是 XXX，是 XXX”这种对立式修辞结构。

语言应客观、自然、清楚，具有专业英语教材的感觉。

### 知识点去重原则

对于同一个核心知识：

- 选择一个最合适的章节详细解释。
- 其他章节如有必要，仅说明它在新语境中的特殊用法。
- 不应多次从头解释相同概念。

例如：

**might** 可以在“表达可能性”章节详细讲解。

之后讨论具体场景时，可以直接使用该结构，不需要反复解释 might 的基础含义。

## 八、综合 Case 的设计

教学文档必须包含 **6 个综合 Case**。

每个 Case 应有明确、不同的场景重点。

每个 Case 使用 Markdown 表格：

### Case 1：具体场景名称

| 角色 | 对话 |
|---|---|
| A | **英文台词** 中文翻译 |
| B | **英文台词** 中文翻译 |
| A | **英文台词** 中文翻译 |
| B | **英文台词** 中文翻译 |
| A | **英文台词** 中文翻译 |
| B | **英文台词** 中文翻译 |

**使用见解**

解释这个 Case 中最值得学习的两个至三个表达、语法或语境特点。

### Case 的要求

1. 每个 Case 具有清楚的交流目标。
2. 每个 Case 至少包含 6 条 A/B 台词。
3. 对话符合真实生活中的交流习惯。
4. 英文应自然，中文翻译准确。
5. 尽量复用前文讲解的重要知识。
6. 同一个 Case 内的表达应能够相互衔接。
7. 不同 Case 应体现不同的情况、问题或交流需求。
8. 不要把原始对话简单拆成六份。
9. 不要让六个 Case 都有相同的发展过程。
10. 每个 Case 的使用见解必须针对该场景的重要内容，避免空泛重复。

根据输入话题重新设计六个 Case，不必照搬示例。

## 九、核心表达总结

教学文档接近结尾时，必须提供一张核心表达总结表。

格式：

| 表达意图 | 核心表达 | 示例 |
|---|---|---|
| 描述身体不适 | I've got ... | **I've got a sore throat.** |
| 表示持续症状 | have been + V-ing | **I've been coughing.** |
| 询问频率 | How often ...? | **How often should I take it?** |
| 表示不确定 | I'm not sure whether ... | **I'm not sure whether it's safe.** |
| 询问建议 | What if ...? | **What if it doesn't get better?** |

### 总结表要求

- 收录本篇最有迁移价值的核心表达。
- 根据实际内容决定数量，通常 25–40 条。
- 允许包含少量重要的单词或固定搭配。
- 优先保留常见、实用、能够直接应用的表达。
- 避免加入大量基础且无需解释的词语。
- 避免为了凑数量而重复相近句式。
- 示例应当简短、准确，能够清楚体现用法。

总结表用于知识回顾和查阅，因此需要控制信息密度。

## 十、重要使用见解

如果该话题涉及多个重要的语言区别，可以在核心表达总结之后增加一个简短的章节：

## 重要使用见解

选取 3–5 个真正值得强调的知识点，集中解释其核心区别或容易误用的地方。

只在有实际补充价值时添加这个章节。

如果前文已经讲清楚，不要再次重复同样内容。

## 十一、篇幅与教学深度

根据原始对话的知识密度确定全文长度。

参考范围：

- 简单的日常交流：8–10 个知识章节。
- 中等复杂度的话题：10–12 个知识章节。
- 涉及较多语法、专业词汇和表达区别的话题：12–14 个知识章节。

六个综合 Case 和核心表达总结作为独立章节。

这些数量用于控制结构，不要求机械凑齐。

### 质量优先原则

- 重要知识可以详细解释。
- 简单知识可以简洁处理。
- 所有章节保持相近的教学质量。
- 不允许通过重复内容增加篇幅。
- 不允许后半部分明显简化或遗漏关键见解。

## 十二、专业知识与事实准确性

某些话题可能涉及医疗、交通、法律、金融或技术知识。

处理这些内容时：

- 严格区分语言用法与专业事实。
- 不编造具体的药品用法、剂量或禁忌。
- 不编造现实中的交通线路、开放时间或商业信息。
- 不根据有限线索断言故障原因。
- 保留需要核实的条件和不确定性。
- 允许在例句中描述假设情况，但不能让学习者误以为是假定场景之外的已确认事实。

教学内容仍以英语语言知识为中心。

## 十三、Markdown 排版规范

全文必须使用标准 Markdown。

标题结构：

# 文档标题

## 一、一级知识章节

### 1. 具体知识点

正文、表格、例句。

## 二、下一个知识章节

依次继续。

### 例句格式

英文加粗，中文紧随其后。

**I've been coughing for two days.**

我已经咳嗽两天了。

表格内：

**I've been coughing for two days.** 我已经咳嗽两天了。

### 其他要求

- 使用简体中文。
- 保留英文表达和句块。
- 重要英语结构加粗。
- 比较多个表达时优先使用表格。
- 避免过大的表格单元格。
- 避免过多层级的标题。
- 不使用冗长的段落开场。
- 不重复解释标题已经清楚表达的信息。
- 不插入表情符号、鼓励口号或学习计划。
- 不使用“不是……而是……”等明显模板化的修辞句式。

## 十四、最终质量检查

正式输出之前，请完整检查结构、语法、教学、内容质量与排版。

## 十五、最终输出要求

直接返回**完整的 Markdown 教学文档**。

不需要：

- 写作计划
- 学习安排
- 教学目标列表
- 课后练习
- 修改日志
- 内容质量评分
- 对 Prompt 的解释
- 额外的开场白

根据原稿内容自主确定最合适的标题、章节和知识安排。

确保文档可以独立阅读，并直接用于英语学习 App。

以下是已经完成润色的情境对话：

${sourceMarkdown.trim()}
`;
}
