/**
 * 阅读题「教学文档」生成提示词。
 * 输入为材料正文与全部理解题，输出按固定教学排版展开的 Markdown。
 */
export type ReadingTeachingQuestionInput = {
  index: number;
  type: string;
  prompt: string;
  options: string[];
  answer: string;
  evidence: string;
};

export function buildReadingTeachingPrompt(input: {
  title?: string;
  source?: string;
  cefr?: string;
  wordCount?: number;
  passageMarkdown: string;
  questions: ReadingTeachingQuestionInput[];
}): string {
  const questions = input.questions.length
    ? input.questions.map((question) => {
      const options = question.options.length
        ? question.options.map((option, index) => `  ${String.fromCharCode(65 + index)}. ${option}`).join('\n')
        : '  （无选项）';
      return [
        `第 ${question.index} 题（${question.type}）`,
        `题干：${question.prompt || '（未填写）'}`,
        `选项：\n${options}`,
        `判定答案：${question.answer || '（未填写）'}`,
        `原文证据：${question.evidence || '（未填写）'}`,
      ].join('\n');
    }).join('\n\n')
    : '（当前没有理解题。只根据材料正文选取关键句，并在文末背景说明中注明题目尚未配置。）';

  return `# 角色与任务

你是一名资深英语阅读教师与学习内容编辑，擅长把英语文章拆成中文学习者能迁移使用的词汇、句块和句型讲解。

请根据下面的**材料正文**和**全部理解题**（题干、选项、判定答案、原文证据），编写一份完整的阅读教学文档。

这份文档给已经能读懂普通英语句子、但还需要系统讲解搭配、句型和句意层次的中文学习者使用。

## 一、文档必须使用的排版

直接输出 Markdown，结构固定为下面这一套，不要改章节名称，不要增删这三个大节。

\`\`\`markdown
# 阅读理解：文章标题

主题：用一句话说明文章讨论的主题范围。

## 一、文章概述

用若干自然段按文章顺序概述内容，写清人物、事件、原因和结果。概述必须覆盖全文，不能只写开头。

核心观点：用一段话概括文章的中心判断，并点出它同时带来的另一面影响或张力。

## 二、文章结构与关键句解析

| 段落 | 核心内容 | 论述作用 |
| --- | --- | --- |
| 第一段 | …… | …… |

### 1. 用中文概括这句的表达功能

> 从正文逐字摘出的英文原句。

对应的准确中文译文。

表达见解：

- **英文表达**：中文释义，并说明它在这句里的用法。

句子理解：

小节标题，例如 As + 从句

用中文解释这个结构或用法，再给 1–2 条可迁移例句。英文例句用加粗，中文紧随其后。

- **As the meeting began, everyone fell silent.** 会议开始时，所有人都安静下来。

## 三、核心词汇与表达

### 1. 核心单词

| 单词 | 中文含义 | 使用见解 |
| --- | --- | --- |
| contain | 控制，遏制 | 可用于疫情、危机和风险控制 |

### 2. 常用句块

| 句块 | 中文含义 | 使用见解 |
| --- | --- | --- |
| within reach of... | 在……可实现的范围内 | 描述经济或能力上的可及性 |

### 3. 实用句型

| 句型 | 中文含义 | 使用见解 | 例句 |
| --- | --- | --- | --- |
| Even with..., ... | 即使有……，仍然…… | 表达让步 | Even with these restrictions, demand continued to grow. 即使有这些限制，需求仍持续增长。 |

文章背景说明：说明文章所处的时间、题材或事实边界。若原文有明显残缺、年份不完整或搭配可疑，在这里说明已按上下文做了必要规范，不要把识别错误写进正文讲解。
\`\`\`

## 二、怎么使用材料正文和理解题

材料正文是讲解的唯一原文来源。引用句必须能在正文中找到，不要改写、合并或另编原句。

理解题用来决定讲什么：

- 被用作「原文证据」的句子必须进入第二节，并讲清楚题干在问什么语言信息。
- 判定答案和干扰项里的关键表达，如果来自正文，要在对应句子或第三节里解释差别。
- 不要另写「参考答案」「答题技巧」或「第 1 题选 B」这样的章节。
- 题目信息应融化进句子讲解：说明这句话支持什么样的理解，而不是公布选项字母。

段落表按正文的自然段或明确的意义段填写。段数与正文一致，不要把整篇文章压成一行。

## 三、关键句的讲解密度

第二节要覆盖文章的论证骨架，并覆盖全部有原文证据的理解题。一篇常规阅读文章通常展开 **8–16 个关键句**；句子少就少讲，句子多或题目证据多就继续写，不要为了凑数重复。

每一句都按同一套内部顺序写全：

1. \`### 序号. 中文功能标题\`。标题描述这句话在做什么，例如「描述多个因素共同推动需求增长」。
2. 用引用块放英文原句。
3. 单独一段中文译文，译文要完整、自然。
4. \`表达见解：\` 下列出本句值得记住的单词和搭配，每条先给英文再给中文。
5. \`句子理解：\` 下讲解 1–3 个真正出现在该句里的结构。每个结构先解释，再给可迁移例句。

讲解要具体到能让学习者换一个话题仍会用。可以比较近义表达，例如 decrease / fall / plummet 的语气差别。不要只写「这是一个状语从句」就结束。

篇幅可以充分展开。重要句子的「句子理解」应包含解释和例句，接近一篇细致的课堂讲义，不要压缩成几条提纲。

## 四、第三节的选词标准

只收这篇材料里真正值得迁移的语言，优先收入：

- 理解题证据和判定答案依赖的词、句块、句型。
- 正文反复出现、或对中文学习者容易用错的表达。
- 能单独拿到别的话题里使用的结构。

核心单词、常用句块、实用句型都要有内容。单词大约 12–24 个，句块大约 10–20 个，句型大约 8–16 个。材料本身较少时按实际数量写，不要编造正文里没有的词来凑表。

句型表的例句必须是新的迁移例句，不要把正文原句再贴一次。

## 五、写作限制

- 使用简体中文，保留英文原文、搭配和例句。
- 教学文档以理解、翻译、比较和举例为主。
- 不要写学习计划、打卡、背诵建议、课后练习或鼓励口号。
- 不要逐段把全文翻译一遍来代替关键句解析；概述负责全文，第二节负责关键句。
- 不要把理解题原样抄成试卷。
- 不使用表情符号。
- 不使用「不是……而是……」这类模板化对照句。
- 历史、科学或时事文章只讲解语言和文中已经写出的事实，不补充无法从材料确认的数据、币种或因果关系。材料没写货币单位时，不要自行补成美元或人民币。
- 全文使用标准 Markdown 表格。表格单元格保持简短。

## 六、输出前检查

确认：

- 标题是 \`# 阅读理解：\` 加文章标题。
- 三个大节名称完全一致。
- 每条关键句都有英文引用、中文译文、表达见解、句子理解。
- 所有理解题的原文证据都能在第二节找到对应讲解。
- 文末有「文章背景说明：」。
- 文档可以独立阅读。

只返回这份 Markdown。不要写开场白、修改说明或对提示词的解释。

## 输入

文章标题：${input.title?.trim() || '（未填写，请根据正文拟定）'}
文章来源：${input.source?.trim() || '（未填写）'}
阅读等级：${input.cefr?.trim() || '（未填写）'}
预计词数：${input.wordCount ? String(input.wordCount) : '（未填写）'}

### 材料正文

${input.passageMarkdown.trim()}

### 理解题

${questions}
`;
}
