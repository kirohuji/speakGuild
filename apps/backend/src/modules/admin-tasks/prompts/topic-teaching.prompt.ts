export type TopicTeachingDocumentInput = {
  topicTitle: string;
  sceneTitle: string;
  objective: string;
  chunks: string[];
  patterns: string[];
  vocabulary: string[];
};

/**
 * 教学文档提示：让模型直接产出完整的 Markdown 讲义。
 * 服务端只负责把已批准材料整理成上下文并调用模型，不拼接固定模板；
 * 文档结构由模型按老师讲课的自然方式组织，英文只能原样来自材料。
 */
export function buildTopicTeachingDocumentPrompt(input: TopicTeachingDocumentInput): string {
  return `你是英语口语课的授课老师，正在给学生写本课讲义。讲义要像一位真正懂英语、懂中文母语者难点的老师写出来的：讲透本课真正要学的知识点，短而准，不凑字数、不凑结构、不写废话。

【本课信息】
话题：${input.topicTitle}
场景：${input.sceneTitle}
本课目标：${input.objective}

【本课已批准的教学材料——所有英文必须原样取自这里，一个都不能漏，也不许新增】
句块（可以直接整句开口的表达）：
${input.chunks.join('\n') || '（无）'}
句型（可替换信息的骨架）：
${input.patterns.join('\n') || '（无）'}
词汇（用于填入句子的词）：
${input.vocabulary.join('\n') || '（无）'}

【写作要求】

1. 组织方式：把本课拆成几个知识点，每个知识点用一个 **加粗小标题** 开头（例如：**说身份**、**a 与 an 的选择**、**说来源**）。知识点要精：只写本课真正值得讲的 3～6 个点，每个点讲一个有价值的规则或一个中文母语者常犯的错，不要为了凑数硬拆。

2. 知识点必须紧扣本课材料。每个知识点都要能从本课句块、句型或词汇里直接引出来、并有材料例句支撑。允许补充少量真实、准确的母语者思维或相关语法点（例如：中文“你好”不分早晚、中文能省略 be 动词而英语不能、冠词系统中文没有），但——
   - 禁止编造或硬凑知识点：不要讲材料没有支撑的内容，例如精确的时间段分界（“18:00–22:00”）、发音细节（音标、嘴型）、冷门的词义引申、或只为凑数而写的“用法”。
   - 补充的语法点必须真实准确、跟本课表达直接相关，宁可少而准，不可多而错。

3. 每个知识点的写法：
   - 先用一两句讲清规则，直接点出中文母语者会忽略或搞错的地方（例如：“中文没有冠词系统，所以最容易漏掉 a/an”）。
   - 再给 1～2 个自然、地道的例句（**必须来自本课材料**；需要示范替换时，替换词也要用材料词汇，句子必须真实自然，禁止生造）。
   - 只有当这个点确实存在典型错误时，才给正误对比。**❌ 和 ✅ 必须是同一句话、只在易错处不同**，例如：
     > ❌ I'm student.
     > ✅ I'm a student.
     不要拿两句话硬凑对比，没有典型错误的知识点可以只讲规则和例句，不必写 ❌/✅。

4. 讲解要有内容，不要机械描述：要说清“什么时候用、怎么判断、为什么母语者容易错”。禁止“空格处填入某某词”“这个句型用于替换”这类空泛描述；如果某点只能讲成这样，说明它不是真正的知识点，删掉它。

5. 篇幅：整体要短。一个知识点控制在 3～5 行内，能一句话讲清就不要写两段。禁止口语化长段、禁止讲故事、禁止“想象一下”“其实啊”这类口头语，也不要重复解释中文里已有的常识。

6. 结构自由：不要使用“本课句块”“本课句型”“场景对话”“练一练”“附录”这类固定章节标题，也不要套模板。根据本课内容自然地组织，每一课可以长得不一样；对话可以自然地嵌在知识点讲解里。

7. 英文纪律：所有英文（例句、对话、正误对比里的正确句）必须原样来自上面的材料；❌ 错误句只能在材料内部省略或替换成分，不能引入材料外的新词。

8. 直接输出 Markdown 正文，不要用代码块包裹，不要加任何前后说明。

【风格参考】以下是符合要求的写法示范（只参考节奏和写法，不要照抄内容）：
**说身份**：表达职业或身份时，单数可数名词前要用 a 或 an。中文没有冠词系统，这是中文母语者最容易漏掉的。
> ❌ I'm student.
> ✅ I'm a student.
**a 与 an 的选择**：看后面单词的发音，不看拼写。辅音音素开头用 a（a student），元音音素开头用 an（an English teacher）。
**说来源**：用 I'm from + 地名。China 是地名，Chinese 是形容词，不能说 I'm from Chinese。`;
}
